create table if not exists public.admin_access_logs (
  id bigint generated by default as identity primary key,
  event text not null check (event in ('page_view', 'login', 'logout')),
  actor_email text,
  page_path text not null default '/admin' check (page_path = '/admin'),
  created_at timestamptz not null default now(),
  constraint admin_access_logs_actor_check
    check (event = 'page_view' or actor_email is not null)
);

alter table public.admin_access_logs enable row level security;

revoke all on public.admin_access_logs from public;
grant select, insert on public.admin_access_logs to anon, authenticated;
grant usage, select on sequence public.admin_access_logs_id_seq to anon, authenticated;

drop policy if exists "Record anonymous admin page views" on public.admin_access_logs;
create policy "Record anonymous admin page views"
  on public.admin_access_logs
  for insert
  to anon
  with check (
    event = 'page_view'
    and actor_email is null
    and page_path = '/admin'
  );

drop policy if exists "Admins record their own access" on public.admin_access_logs;
drop policy if exists "Authenticated users record their own page views" on public.admin_access_logs;
create policy "Authenticated users record their own page views"
  on public.admin_access_logs
  for insert
  to authenticated
  with check (
    page_path = '/admin'
    and actor_email = (auth.jwt() ->> 'email')
    and (
      event = 'page_view'
      or (
        (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
        and event in ('login', 'logout')
      )
    )
  );

drop policy if exists "Admins read admin access history" on public.admin_access_logs;
create policy "Admins read admin access history"
  on public.admin_access_logs
  for select
  to authenticated
  using (
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );
