create or replace function public.create_client_booking(
  p_name text,
  p_room text,
  p_date date,
  p_checkout_date date
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_price numeric;
  v_booking_ref uuid;
begin
  if v_user_id is null then
    raise exception 'Sign in before creating a reservation';
  end if;

  if (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin' then
    raise exception 'Use a client account to create a client reservation';
  end if;

  if coalesce(trim(p_name), '') = '' or p_date is null or p_checkout_date is null then
    raise exception 'Complete the reservation details before booking';
  end if;

  if p_date < current_date then
    raise exception 'Check-in date cannot be in the past';
  end if;

  if p_checkout_date <= p_date then
    raise exception 'Check-out date must be after check-in date';
  end if;

  -- Keep this server-side price list aligned with src/features/rooms/roomData.js.
  v_price := case p_room
    when 'Single Room' then 1500
    when 'Double Room' then 2500
    when 'Deluxe Room' then 3500
    else null
  end;

  if v_price is null then
    raise exception 'Select a valid room type';
  end if;

  perform pg_advisory_xact_lock(pg_catalog.hashtextextended(p_room, 0));

  if exists (
    select 1
    from public.bookings as existing
    where existing.room = p_room
      and lower(coalesce(existing.status, '')) not in ('cancelled', 'canceled', 'waiting')
      and existing.date < p_checkout_date
      and existing.checkout_date > p_date
  ) then
    raise exception 'Room is unavailable for the selected dates; join the waiting list instead';
  end if;

  insert into public.bookings (
    user_id,
    name,
    room,
    date,
    checkout_date,
    price,
    status
  )
  values (
    v_user_id,
    trim(p_name),
    p_room,
    p_date,
    p_checkout_date,
    v_price,
    'Booked'
  )
  returning client_booking_ref into v_booking_ref;

  return v_booking_ref;
end;
$$;

create or replace function public.cancel_client_booking(p_client_booking_ref uuid)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_updated boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Sign in before cancelling a reservation';
  end if;

  update public.bookings
  set status = 'Cancelled'
  where client_booking_ref = p_client_booking_ref
    and user_id = auth.uid()
    and lower(coalesce(status, '')) not in ('cancelled', 'canceled', 'completed')
    and checkout_date > current_date
  returning true into v_updated;

  return coalesce(v_updated, false);
end;
$$;

create or replace function public.admin_cancel_booking(p_client_booking_ref uuid)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_updated boolean := false;
begin
  if coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' then
    raise exception 'Admin access is required to cancel another account reservation';
  end if;

  update public.bookings
  set status = 'Cancelled'
  where client_booking_ref = p_client_booking_ref
    and lower(coalesce(status, '')) not in ('cancelled', 'canceled', 'completed')
    and checkout_date > current_date
  returning true into v_updated;

  return coalesce(v_updated, false);
end;
$$;

