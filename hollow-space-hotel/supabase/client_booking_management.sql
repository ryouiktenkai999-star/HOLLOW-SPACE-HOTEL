do $$
declare
  required_column text;
begin
  if to_regclass('public.bookings') is null then
    raise exception 'Expected public.bookings to exist before applying client_booking_management.sql';
  end if;

  foreach required_column in array array['name', 'room', 'date', 'checkout_date', 'price', 'status']
  loop
    if not exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'bookings'
        and column_name = required_column
    ) then
      raise exception 'Expected public.bookings.% to exist; update this migration to match the live schema first', required_column;
    end if;
  end loop;

  if (
    select udt_name
    from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings' and column_name = 'date'
  ) <> 'date'
  or (
    select udt_name
    from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings' and column_name = 'checkout_date'
  ) <> 'date' then
    raise exception 'public.bookings.date and checkout_date must use the PostgreSQL date type';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name = 'status' and data_type not in ('text', 'character varying')
  ) or exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name in ('name', 'room')
      and data_type not in ('text', 'character varying')
  ) then
    raise exception 'public.bookings.name, room, and status must be text columns';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name = 'price'
      and data_type not in ('numeric', 'smallint', 'integer', 'bigint', 'real', 'double precision')
  ) then
    raise exception 'public.bookings.price must be a numeric column';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name = 'created_at'
      and data_type not in ('timestamp with time zone', 'timestamp without time zone')
  ) then
    raise exception 'public.bookings.created_at must be a timestamp column';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name = 'user_id' and udt_name <> 'uuid'
  ) or exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'bookings'
      and column_name = 'client_booking_ref' and udt_name <> 'uuid'
  ) then
    raise exception 'public.bookings.user_id and client_booking_ref must be uuid columns';
  end if;
end;
$$;

